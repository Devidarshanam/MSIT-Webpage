/**
 * Returns an appropriate SVG icon matching a title, label, or emoji.
 */
export function getSmartIcon(keyOrEmoji, defaultSize = 20) {
  const str = String(keyOrEmoji || '').toLowerCase();
  
  if (str.includes('briefcase') || str.includes('💼') || str.includes('industry') || str.includes('job') || str.includes('career') || str.includes('co-op')) {
    return <BriefcaseIcon size={defaultSize} />;
  }
  if (str.includes('building') || str.includes('🏛️') || str.includes('institute') || str.includes('campus') || str.includes('hyderabad') || str.includes('ecosystem')) {
    return <BuildingIcon size={defaultSize} />;
  }
  if (str.includes('rocket') || str.includes('🚀') || str.includes('builder') || str.includes('venture') || str.includes('startup')) {
    return <RocketIcon size={defaultSize} />;
  }
  if (str.includes('zap') || str.includes('⚡') || str.includes('obsolescence') || str.includes('resilience') || str.includes('fast')) {
    return <ZapIcon size={defaultSize} />;
  }
  if (str.includes('users') || str.includes('👥') || str.includes('mentor') || str.includes('practitioner') || str.includes('peers')) {
    return <UsersIcon size={defaultSize} />;
  }
  if (str.includes('target') || str.includes('🎯') || str.includes('value') || str.includes('focus') || str.includes('problem')) {
    return <TargetIcon size={defaultSize} />;
  }
  if (str.includes('grad') || str.includes('🎓') || str.includes('degree') || str.includes('academic') || str.includes('master')) {
    return <GraduationCapIcon size={defaultSize} />;
  }
  if (str.includes('calendar') || str.includes('date') || str.includes('intake') || str.includes('january')) {
    return <CalendarIcon size={defaultSize} />;
  }
  if (str.includes('clock') || str.includes('duration') || str.includes('tenure') || str.includes('time')) {
    return <ClockIcon size={defaultSize} />;
  }
  if (str.includes('award') || str.includes('legacy') || str.includes('vision') || str.includes('turing') || str.includes('raj reddy')) {
    return <AwardIcon size={defaultSize} />;
  }
  if (str.includes('ai') || str.includes('spark') || str.includes('smart') || str.includes('cognitive') || str.includes('autonomous')) {
    return <SparklesIcon size={defaultSize} />;
  }
  if (str.includes('tech') || str.includes('system') || str.includes('cpu') || str.includes('computing') || str.includes('software')) {
    return <CpuIcon size={defaultSize} />;
  }
  if (str.includes('check') || str.includes('eligibility') || str.includes('criteria') || str.includes('verified')) {
    return <ShieldCheckIcon size={defaultSize} />;
  }
  if (str.includes('book') || str.includes('curriculum') || str.includes('learn') || str.includes('study')) {
    return <BookOpenIcon size={defaultSize} />;
  }
  
  return <CheckCircleIcon size={defaultSize} />;
}
